#!/usr/bin/env python3
"""Generate manuscript tables from the frozen 300-query evaluation evidence."""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path
from statistics import fmean


ROOT = Path(__file__).resolve().parents[2]
DEFAULT_RESULTS = ROOT / "backend/tests/evidence/eval_results_300.jsonl"
DEFAULT_OUTPUT = ROOT / "article/generated_results_tables.tex"
METHODS = (
    "KnowledgeHub_QuadPath",
    "Dense_Only",
    "BM25_Only",
    "Graph_Only",
    "Hybrid_Dual",
)
METHOD_LABELS = {
    "KnowledgeHub_QuadPath": "KnowledgeHub QuadPath",
    "Dense_Only": "Dense-Only",
    "BM25_Only": "BM25-Only",
    "Graph_Only": "Graph-Only",
    "Hybrid_Dual": "Hybrid-Dual",
}
METRICS = ("recall@5", "recall@10", "mrr@10", "map@10", "ndcg@10", "hopRecall@10")
TIMINGS = ("t_embed", "t_bm25", "t_dense", "t_graph", "t_rrf", "t_rerank", "t_total")


def read_rows(path: Path) -> list[dict]:
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def latex_escape(value: str) -> str:
    return value.replace("&", r"\&").replace("_", r"\_")


def aggregate(rows: list[dict]) -> dict[str, dict[str, float]]:
    grouped: dict[str, list[dict]] = defaultdict(list)
    for row in rows:
        grouped[str(row["method"])].append(row)
    if set(grouped) != set(METHODS) or any(len(grouped[m]) != 300 for m in METHODS):
        raise ValueError("expected exactly 300 rows for each frozen method")
    return {
        method: {
            **{metric: fmean(float(row[metric]) for row in grouped[method]) for metric in METRICS},
            **{timing: fmean(float(row[timing]) for row in grouped[method]) / 1000.0 for timing in TIMINGS},
        }
        for method in METHODS
    }


def render(summary: dict[str, dict[str, float]], query_count: int, unique_texts: int) -> str:
    lines = [
        "% Auto-generated by scripts/eval_suite/generate_latex_tables.py.",
        "% Do not edit metric values by hand; regenerate from eval_results_300.jsonl.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\footnotesize",
        f"\\caption{{Descriptive retrieval scores over {query_count} v2 records ({unique_texts} distinct question texts).}}",
        r"\label{tab:retrieval-results}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{lrrrrrr}",
        r"\toprule",
        r"Pipeline & Recall@5 & Recall@10 & MRR@10 & MAP@10 & NDCG@10 & HopRecall@10 \\",
        r"\midrule",
    ]
    for method in METHODS:
        row = summary[method]
        label = latex_escape(METHOD_LABELS[method])
        values = " & ".join(f"{row[m]:.4f}" for m in METRICS)
        lines.append(f"{label} & {values} \\\\")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}}",
        r"\begin{flushleft}\footnotesize",
        r"All values are row-weighted means from the v2 offline deterministic runner. QuadPath fuses the stored BM25, hashed-vector and metadata-family rankings; Dense is a hashed-vector proxy and Graph is a metadata-family proxy. No Qwen embedding or DeepSeek generation is used in this retrieval run; NDCG is evaluated against the frozen qrels.",
        r"\end{flushleft}",
        r"\end{table}",
        "",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\footnotesize",
        r"\caption{Mean retrieval-stage time by pipeline (microseconds).}",
        r"\label{tab:timing_300}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{lrrrrrrr}",
        r"\toprule",
        r"Pipeline & Embed & BM25 & Dense & Graph & RRF & Rerank & Total \\",
        r"\midrule",
    ])
    for method in METHODS:
        row = summary[method]
        values = " & ".join(f"{row[m]:.1f}" for m in TIMINGS)
        lines.append(f"{latex_escape(METHOD_LABELS[method])} & {values} \\\\")
    lines.extend([
        r"\bottomrule",
        r"\end{tabular}}",
        r"\begin{flushleft}\footnotesize",
        r"Timing fields are collected with Python \texttt{perf\_counter\_ns}; they are diagnostic wall-clock measurements on the local runner, not a production SLA.",
        r"\end{flushleft}",
        r"\end{table}",
        "",
    ])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    rows = read_rows(args.results)
    summary = aggregate(rows)
    query_count = len({str(row.get("queryId")) for row in rows})
    unique_texts = len({" ".join(str(row.get("query", "")).casefold().split()) for row in rows})
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(summary, query_count, unique_texts), encoding="utf-8")
    print(args.output)


if __name__ == "__main__":
    main()
